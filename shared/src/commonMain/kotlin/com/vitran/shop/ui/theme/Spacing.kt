package com.vitran.shop.ui.theme

import androidx.compose.ui.unit.dp

/**
 * Semantic spacing scale. Prefer these over raw `.dp` paddings/gaps.
 * Name by scale step (`md`), not by pixel value (`spacing12`).
 */
object VitranSpacing {
    val xs = 4.dp
    val sm = 8.dp
    val md = 12.dp
    val lg = 16.dp
    val xl = 20.dp
    val xxl = 24.dp
    val xxxl = 32.dp
}
